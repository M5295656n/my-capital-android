package ru.mycapital.app.data

import java.io.File
import java.time.LocalDate
import java.time.ZoneId
import org.json.JSONObject
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test

/**
 * CI-only live audit: the preceding source-validation step downloads the current
 * Dohod/Smart-Lab datasets. This test then runs the real Kotlin parsers, provider
 * selection and production forecast function over the combined indexed universe.
 */
class DividendForecastLiveAuditTest {
    @Test
    fun productionForecastsDoNotMultiplyStableAnnualPaymentCountsAcrossAllIndexedIssuers() {
        val fixtureFile = File("app/build/dividend-audit/fixtures.json")
        assumeTrue("Live dividend fixtures are generated by the CI source-validation step", fixtureFile.isFile)

        val root = JSONObject(fixtureFile.readText(Charsets.UTF_8))
        val dohod = root.optJSONObject("dohod") ?: JSONObject()
        val smartlab = root.optJSONObject("smartlab") ?: JSONObject()
        val dohodIndex = dohod.optJSONObject("index") ?: JSONObject()
        val smartlabIndex = smartlab.optJSONObject("index") ?: JSONObject()
        val dohodHistories = dohod.optJSONObject("histories") ?: JSONObject()
        val smartlabHistories = smartlab.optJSONObject("histories") ?: JSONObject()
        val tickers = linkedSetOf<String>()
        val dohodTickers = dohodIndex.optJSONArray("tickers")
        val smartlabTickers = smartlabIndex.optJSONArray("tickers")
        if (dohodTickers != null) {
            for (i in 0 until dohodTickers.length()) tickers += dohodTickers.optString(i).uppercase()
        }
        if (smartlabTickers != null) {
            for (i in 0 until smartlabTickers.length()) tickers += smartlabTickers.optString(i).uppercase()
        }

        val today = LocalDate.now(ZoneId.of("Europe/Moscow"))
        var audited = 0
        val violations = mutableListOf<String>()
        tickers.sorted().forEach { ticker ->
            val dohodPayload = dohodHistories.optJSONObject(ticker)
            val smartlabPayload = smartlabHistories.optJSONObject(ticker)
            val dohodRows = dohodPayload?.let {
                parseDohodHistoricalDividends(ticker, dohodIndex.toString(), it.toString(), today)
            }
            val smartlabRows = smartlabPayload?.let {
                parseSmartlabHistoricalDividends(ticker, smartlabIndex.toString(), it.toString(), today)
            }
            val history = selectMoreCompleteDividendHistory(dohodRows, smartlabRows) ?: return@forEach
            if (history.size < 2) return@forEach

            val latestYears = history.groupBy { it.recordDate.year }
                .toSortedMap().entries.toList().takeLast(2)
            if (latestYears.size != 2) return@forEach
            if (latestYears[1].key - latestYears[0].key != 1) return@forEach
            val previousCount = latestYears[0].value.size
            val latestCount = latestYears[1].value.size
            if (previousCount != latestCount || previousCount !in 1..4) return@forEach

            val forecasts = calculateHistoricalDividendForecasts(
                ticker = ticker,
                dividends = history,
                today = today,
                horizonMonths = 24
            )
            audited++
            val maximumExpected = previousCount * 2
            if (forecasts.size > maximumExpected) {
                violations += "$ticker: $previousCount paid events/year in both latest years, " +
                    "but production algorithm generated ${forecasts.size} forecasts in 24 months"
            }
        }

        assertTrue(
            "Production dividend forecast overcount detected across live issuers: " +
                violations.take(30).joinToString("; "),
            violations.isEmpty()
        )
        assertTrue("Expected a meaningful live audit universe, audited only $audited issuers", audited >= 20)
        println("LIVE DIVIDEND FORECAST AUDIT: indexed=${tickers.size}, audited=$audited, violations=${violations.size}")
    }
}
